% 4.	Common functions
% (a)	Consider, x = pi/3 and find sin(x), cos(x), tan(x), exp(x), log(x), sqrt(x), round(x)
% (b)	Consider, z = 3+4 * i (a complex number) and find abs(z), angle(z)
% (c)	Consider, a = 0.866 and find acos(a), asin(a), atan(a)

% (a)
x = pi/3

sin_x     = sin(x)
cos_x     = cos(x)
tan_x     = tan(x)
exp_x     = exp(x)
log_x     = log(x)
sqrt_x    = sqrt(x)
round_x   = round(x)

% (b)
z = 3 + 4i

abs_z     = abs(z)
angle_z   = angle(z) % = atan(4/3) in rad

% (c)
a = 0.866

acos_a    = acos(a)
asin_a    = asin(a)
atan_a    = atan(a)